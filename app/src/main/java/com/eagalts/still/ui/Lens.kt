package com.eagalts.still.ui

import kotlin.math.abs
import kotlin.math.min
import kotlin.math.pow

/**
 * «Линза» — главный образ ленты Still. Сетка под ней обычная и ровная (её считает LazyGrid), а линза только
 * показывает её иначе: кадр у центра экрана крупный и яркий, к краям — меньше, ближе к середине и уходит в тень.
 * Листаешь — каждый кадр «набухает», проходя через центр.
 *
 * Одна функция на всё: по ней рисуются плитки, ловится касание (тап попадает в тот кадр, который видно)
 * и считается, откуда вылетает фото в просмотр. Без аллокаций — пишет в [out].
 *
 * Сила [k] 0…1: линза работает, когда смотришь, и уступает, когда делаешь (быстрая прокрутка, выбор,
 * отдаление) — тогда это обычная плотная сетка.
 */
object Lens {
    /** Масштаб у края экрана при полной силе: не мельче — иначе пальцу неудобно. */
    const val EDGE = 0.74f
    /** Кадр в самом центре чуть меньше ячейки — между кадрами воздух. */
    const val CENTER = 0.95f

    const val SCALE = 0
    const val TX = 1
    const val TY = 2
    const val SHADE = 3

    /**
     * [cx], [cy] — центр ячейки в координатах видимой области сетки; [w], [h] — её размер.
     * В [out]: масштаб, сдвиг по x и y (к центру) и тень 0…1.
     */
    fun pose(cx: Float, cy: Float, w: Float, h: Float, k: Float, out: FloatArray) {
        val kk = k.coerceIn(0f, 1f)
        val x = cy - h / 2f
        val a = (abs(x) / (h / 2f)).coerceAtMost(1.4f)
        val fall = a.pow(1.5f)
        out[SCALE] = 1f - kk * ((1f - CENTER) + (CENTER - EDGE) * fall)
        // ряды у краёв подтягиваются к центру: линза сжимает поле зрения, а не просто уменьшает кадры
        out[TY] = -x * kk * 0.1f * min(a, 1.2f)
        out[TX] = -(cx - w / 2f) * kk * 0.07f * a
        out[SHADE] = (kk * 0.62f * a * a).coerceIn(0f, 0.72f)
    }

    /** Сила линзы для числа столбцов: крупно — полная, на 5 — половина, месяцы и годы — плоская сетка. */
    fun strengthFor(cols: Int): Float = when { cols <= 3 -> 1f; cols <= 5 -> 0.5f; else -> 0f }
}
